<?php
/**
 * Regenerates the layout/CSS golden fixture from the PHP implementation.
 *
 * Usage: php bin/contract-fixtures.php
 * Review the diff before committing: the TypeScript implementation is tested against the result,
 * so an unreviewed regeneration would hide a divergence instead of revealing it.
 *
 * @package sw-sliderman
 */

declare(strict_types=1);

use SW\Slider\Domain\LayoutResolver;
use SW\Slider\Domain\RichText;
use SW\Slider\Rendering\StyleSerializer;

require dirname( __DIR__ ) . '/vendor/autoload.php';

$sws_root     = dirname( __DIR__ );
$sws_document = json_decode( (string) file_get_contents( $sws_root . '/tests/fixtures/documents/valid/basic.json' ), true, 512, JSON_THROW_ON_ERROR );
$sws_refs     = array();
foreach ( $sws_document['fontRefs'] as $sws_ref ) {
	$sws_refs[ $sws_ref['id'] ] = $sws_ref;
}

$sws_out = array(
	'description' => 'Golden layout/CSS results for documents/valid/basic.json (generated by bin/contract-fixtures.php, reviewed by hand).',
	'cases'       => array(),
);
foreach ( LayoutResolver::BREAKPOINTS as $sws_breakpoint ) {
	$sws_stage = $sws_document['breakpoints'][ $sws_breakpoint ];
	foreach ( $sws_document['slides'] as $sws_slide ) {
		foreach ( $sws_slide['layers'] as $sws_layer ) {
			$sws_resolved       = LayoutResolver::resolve_layer( $sws_layer, $sws_breakpoint, $sws_document['breakpoints'] );
			$sws_declarations   = StyleSerializer::layer_declarations( $sws_resolved, (float) $sws_stage['stageWidth'], (float) $sws_stage['stageHeight'], $sws_refs, 'shape' === $sws_layer['type'] ? $sws_layer['content']['kind'] : null );
			$sws_out['cases'][] = array(
				'breakpoint' => $sws_breakpoint,
				'layer'      => $sws_layer['id'],
				'box'        => $sws_resolved['box'],
				'boxCss'     => StyleSerializer::serialize( $sws_declarations['box'] ),
				'bodyCss'    => StyleSerializer::serialize( $sws_declarations['body'] ),
				'stateCss'   => 'button' === $sws_layer['type'] ? StyleSerializer::button_state_css( '.sws-l-' . $sws_layer['id'], $sws_layer['content'] ) : '',
			);
		}
	}
}
file_put_contents( $sws_root . '/tests/fixtures/css/basic.json', json_encode( $sws_out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION ) . "\n" );
echo "tests/fixtures/css/basic.json written\n";

$sws_rich_file = $sws_root . '/tests/fixtures/rich/render.json';
$sws_rich      = json_decode( (string) file_get_contents( $sws_rich_file ), true, 512, JSON_THROW_ON_ERROR );
foreach ( $sws_rich['cases'] as $sws_index => $sws_case ) {
	$sws_rich['cases'][ $sws_index ]['html'] = RichText::to_html( $sws_case['rich'] );
}
file_put_contents( $sws_rich_file, json_encode( $sws_rich, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION ) . "\n" );
echo "tests/fixtures/rich/render.json written\n";

$sws_background = json_decode( (string) file_get_contents( $sws_root . '/tests/fixtures/documents/valid/background.json' ), true, 512, JSON_THROW_ON_ERROR );
$sws_bg_out     = array(
	'description' => 'Golden slide overlay/focal CSS for documents/valid/background.json (generated by bin/contract-fixtures.php, reviewed by hand).',
	'slides'      => array(),
	'images'      => array(),
);
foreach ( $sws_background['slides'] as $sws_slide ) {
	$sws_bg_out['slides'][] = array(
		'slide' => $sws_slide['id'],
		'css'   => StyleSerializer::slide_background_css( '.sws-s-test .sws-sl-' . $sws_slide['id'], $sws_slide['background'] ),
	);
	foreach ( $sws_slide['layers'] as $sws_layer ) {
		if ( 'image' === $sws_layer['type'] ) {
			$sws_bg_out['images'][] = array(
				'layer' => $sws_layer['id'],
				'css'   => StyleSerializer::image_focal_css( '.sws-s-test .sws-l-' . $sws_layer['id'], $sws_layer['content'] ),
			);
		}
	}
}
file_put_contents( $sws_root . '/tests/fixtures/css/background.json', json_encode( $sws_bg_out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_PRESERVE_ZERO_FRACTION ) . "\n" );
echo "tests/fixtures/css/background.json written\n";
